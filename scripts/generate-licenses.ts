import { dirname, join } from "node:path";
import { z } from "zod";

const licenseSchema = z.object({
  type: z.string().optional(),
  url: z.string().optional(),
});
const packageJsonSchema = z.object({
  name: z.string().optional(),
  version: z.string().optional(),
  private: z.boolean().optional(),
  license: z.union([z.string(), licenseSchema]).optional(),
  licenses: z.array(licenseSchema).optional(),
  dependencies: z.record(z.string(), z.string()).default({}),
  optionalDependencies: z.record(z.string(), z.string()).default({}),
});
type PackageJson = z.infer<typeof packageJsonSchema>;

const root = dirname(import.meta.dir);
const output = join(root, "packages/site/public/THIRD-PARTY-LICENSES.txt");
const packages = new Map<
  string,
  { license: string; notice: string; names: Set<string> }
>();
const visited = new Set<string>();

async function resolvePackage(name: string, from: string) {
  let directory = from;
  while (true) {
    const packageJson = join(directory, "node_modules", name, "package.json");
    if (await Bun.file(packageJson).exists()) return packageJson;
    const parent = dirname(directory);
    if (parent === directory) return;
    directory = parent;
  }
}

async function textFiles(directory: string, pattern: RegExp) {
  const names = [];
  for await (const name of new Bun.Glob("*").scan({
    cwd: directory,
    onlyFiles: true,
  })) {
    if (pattern.test(name)) names.push(name);
  }
  names.sort();
  return Promise.all(
    names.map((name) => Bun.file(join(directory, name)).text()),
  );
}

function clean(text: string) {
  return text
    .replace(/\r\n?/g, "\n")
    .replace(/[ \t]+$/gm, "")
    .trim();
}

async function licenseText(directory: string, manifest: PackageJson) {
  if (
    typeof manifest.license === "string" &&
    /^see license in /i.test(manifest.license)
  ) {
    const file = manifest.license
      .replace(/^see license in /i, "")
      .replace(/["'<>]/g, "");
    if (await Bun.file(join(directory, file)).exists())
      return Bun.file(join(directory, file)).text();
  }

  const files = await textFiles(directory, /^(licen[cs]e|copying)([-.].*)?$/i);
  if (files.length > 0) return files.join("\n\n");
  if (typeof manifest.license === "string") return manifest.license;
  if (manifest.license?.type || manifest.license?.url) {
    return manifest.license.type ?? manifest.license.url;
  }
  const licenses = manifest.licenses
    ?.map(({ type, url }) => type ?? url)
    .filter(Boolean);
  if (licenses?.length) return licenses.join(" OR ");
}

async function visit(packageJson: string, include = false) {
  if (visited.has(packageJson)) return;
  visited.add(packageJson);

  const directory = dirname(packageJson);
  const manifest = packageJsonSchema.parse(await Bun.file(packageJson).json());
  if (include && !manifest.private) {
    if (!manifest.name || !manifest.version)
      throw new Error(`Missing package identity in ${packageJson}`);
    const rawLicense = await licenseText(directory, manifest);
    if (!rawLicense)
      throw new Error(
        `No license found for ${manifest.name}@${manifest.version}`,
      );
    const license = clean(rawLicense);
    const notice = clean(
      (await textFiles(directory, /^notice([-.].*)?$/i)).join("\n\n"),
    );
    const key = `${license}\0${notice}`;
    const group = packages.get(key) ?? {
      license,
      notice,
      names: new Set(),
    };
    group.names.add(`${manifest.name}@${manifest.version}`);
    packages.set(key, group);
  }

  const required = Object.keys(manifest.dependencies);
  const optional = Object.keys(manifest.optionalDependencies);
  for (const name of new Set([...required, ...optional])) {
    const dependency = await resolvePackage(name, directory);
    if (dependency) await visit(dependency, true);
    else if (required.includes(name))
      throw new Error(`Cannot resolve ${name} from ${packageJson}`);
  }
}

const projects = ["package.json"];
for await (const packageJson of new Bun.Glob("packages/*/package.json").scan(
  root,
)) {
  projects.push(packageJson);
}
projects.sort();
for (const packageJson of projects) await visit(join(root, packageJson));

const sections = [...packages.values()]
  .sort((a, b) => [...a.names][0].localeCompare([...b.names][0]))
  .map(({ license, notice, names }) => {
    const heading = [...names]
      .sort()
      .map((name) => ` - ${name}`)
      .join("\n");
    return `${heading}\n\n${license}${notice ? `\n\nNOTICE\n\n${notice}` : ""}`;
  });
const contents = [
  "Third-party licenses for CRS",
  "Generated by `bun run licenses`; do not edit manually.",
  "Covers installed runtime and optional dependencies of the CRS workspaces.",
  "Platform-specific optional packages depend on the build environment.",
  "",
  ...sections.flatMap((section) => [section, "", "-----------", ""]),
].join("\n");

await Bun.write(output, contents);
const packageCount = [...packages.values()].reduce(
  (count, group) => count + group.names.size,
  0,
);
console.log(`Wrote licenses for ${packageCount} packages to ${output}`);
